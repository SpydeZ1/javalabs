#!/bin/bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
CREATE USER translation_app WITH PASSWORD '${DB_APP_PASSWORD}';

GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO translation_app;
GRANT USAGE ON SCHEMA public TO translation_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO translation_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO translation_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO translation_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO translation_app;

REVOKE CREATE ON SCHEMA public FROM translation_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
EOSQL
